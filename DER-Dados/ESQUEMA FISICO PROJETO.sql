

CREATE TABLE OPERADORES (
id_operador INT AUTO PRIMARY KEY PRIMARY KEY,
nome VARCHAR(60),
telefone VARHAR(20) NOT NULL,
noturno ENUM('NOTURNO'),
diurno ENUM('DIURNO'),
id_ordem INT AUTO INCREMENT PRIMARY KEY
)

CREATE TABLE ORDEM_PRODUCAO (
id_ordem INT AUTO INCREMENT PRIMARY KEY PRIMARY KEY,
data_inicio DATE NOT NULL,
prioridade ENUM (' BAIXA','ALTA'),
prazo DATE,
id_producao INT AUTO INCREMENT PRIMARY KEY
)

CREATE TABLE ITEM_PRODUCAO (
id_producao INT AUTO INCREMENT PRIMARY KEY PRIMARY KEY,
quantidade INT NOT NULL,
inativo ENUM('INATIVO'),
ativo ENUM('ATIVO'),
turno_producao ENUM(' NOTURNO','DIURNO')
)

CREATE TABLE PRODUTO (
id_produto INT AUTO INCREMENT PRIMARY KEY PRIMARY KEY,
quantidade INT,
descrição TEXT,
preco DECIMAL (10,2),
id_producao INT AUTO INCREMENT PRIMARY KEY,
FOREIGN KEY(id_producao) REFERENCES ITEM_PRODUCAO (id_producao)
)

CREATE TABLE MAQUINAS (
id_maquina INT AUTO INCREMENT PRIMARY KEY PRIMARY KEY,
modelo VARCHAR(60),
operador VARCHAR(60),
ligado ENUM('LIGADO'),
desligado ENUM('DESLIGADO'),
id_ordem INT AUTO INCREMENT PRIMARY KEY,
FOREIGN KEY(id_ordem) REFERENCES ORDEM_PRODUCAO (id_ordem)
)

ALTER TABLE OPERADORES ADD FOREIGN KEY(id_ordem) REFERENCES ORDEM_PRODUCAO (id_ordem)
ALTER TABLE ORDEM_PRODUCAO ADD FOREIGN KEY(id_producao) REFERENCES ITEM_PRODUCAO (id_producao)
